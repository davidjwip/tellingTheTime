/**
 * Artefact generation: the tests write viewable files.
 *
 * No browser, no Playwright, no image encoder. The renderer already builds real DOM, so an SVG face
 * serialises to a `.svg` a human can open, and a whole screen serialises into a standalone `.html`
 * with the stylesheet inlined. Both are text, so they diff in review like code.
 *
 * They double as a visual-regression gate: if a committed artefact changes, the test fails and names
 * it, rather than quietly redrawing the thing you were comparing against. Re-bless deliberately:
 *
 *     UPDATE_ARTEFACTS=1 npx vitest run
 *
 * When Playwright arrives this stays useful — these are the reference images it will be compared to,
 * and they do not need a browser to produce. See docs/visual-artefacts.md.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const ARTEFACT_DIR = 'artefacts';

export class ArtefactChangedError extends Error {
  constructor(path: string) {
    super(
      `${path} changed. Look at the diff, and if the change is intended re-bless with ` +
        `UPDATE_ARTEFACTS=1 npx vitest run`,
    );
    this.name = 'ArtefactChangedError';
  }
}

function write(path: string, body: string): string {
  const full = join(ARTEFACT_DIR, path);
  mkdirSync(dirname(full), { recursive: true });

  if (existsSync(full) && process.env.UPDATE_ARTEFACTS !== '1') {
    const before = readFileSync(full, 'utf8');
    if (before !== body) {
      writeFileSync(`${full}.actual`, body);
      throw new ArtefactChangedError(full);
    }
    return full;
  }

  writeFileSync(full, body);
  return full;
}

/** Serialise an element (usually the <svg> face) to a standalone SVG document. */
export function writeSvg(name: string, element: Element): string {
  const source = element.outerHTML;
  return write(
    `${name}.svg`,
    `<?xml version="1.0" encoding="UTF-8"?>\n${source}\n`,
  );
}

/**
 * Serialise a screen into a single self-contained HTML file.
 *
 * The card is centred on the page so it reads as an app on a tablet, which is how it will be used.
 */
export function writeScreen(name: string, element: Element, title: string): string {
  const css = readFileSync('src/styles.css', 'utf8');
  return write(
    `${name}.html`,
    `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<style>
${css}
/* artefact preview only: this file is generated by the test suite, not shipped */
body { display: flex; align-items: flex-start; justify-content: center; }
</style>
</head>
<body>
${element.outerHTML}
</body>
</html>
`,
  );
}
